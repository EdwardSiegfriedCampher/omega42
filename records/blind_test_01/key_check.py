#!/usr/bin/env python3
"""Blind test 01 -- computes every answer recorded in key.txt (standard library only)."""
import itertools, cmath, math
from fractions import Fraction as Fr
from collections import Counter
V = list(itertools.product(range(9), repeat=2))
q = {x: Fr((x[0] ** 2 + x[0] * x[1] - x[1] ** 2) % 9, 9) for x in V}
add = lambda x, y: ((x[0] + y[0]) % 9, (x[1] + y[1]) % 9)
beta = lambda x, y: (q[add(x, y)] - q[x] - q[y]) % 1
print("Q1 nondegenerate:", all(any(beta(x, y) != 0 for y in V) for x in V if x != (0, 0)))
gs = sum(cmath.exp(2j * math.pi * float(q[x])) for x in V) / 9
print("Q2 Gauss sum: %.9f%+.9fi -> c = 0 mod 8" % (gs.real, gs.imag))
GL = [((a, b), (c, d)) for a, b, c, d in itertools.product(range(9), repeat=4) if math.gcd((a * d - b * c) % 9, 9) == 1]
app = lambda M, x: ((M[0][0] * x[0] + M[0][1] * x[1]) % 9, (M[1][0] * x[0] + M[1][1] * x[1]) % 9)
su9sq = lambda y: Fr(4 * (y[0] ** 2 + y[1] ** 2) % 9, 9)
tc = lambda y: Fr(y[0] * y[1] % 9, 9)
iso = [M for M in GL if all(su9sq(app(M, x)) == q[x] for x in V)]
print("Q3 isometric to SU(9)_1 x SU(9)_1 (q = 4(a^2+b^2)/9): %s, e.g. %s; isometric to the Z9 toric code: %s"
      % (bool(iso), iso[0], any(all(tc(app(M, x)) == q[x] for x in V) for M in GL)))
print("Q3 SU(9)_1 spins h_a = a(9-a)/18 equal 4a^2/9 mod 1:", all(Fr(a * (9 - a), 18) % 1 == Fr(4 * a * a % 9, 9) for a in range(9)))
bos = sorted(x for x in V if q[x] == 0)
print("Q4 bosons:", len(bos), bos, "| subgroup (3Z/9)^2:", bos == sorted((3 * a % 9, 3 * b % 9) for a in range(3) for b in range(3)),
      "| isotropic:", all(beta(x, y) == 0 for x in bos for y in bos))
U = [M for M in GL if all(q[app(M, x)] == q[x] for x in V)]
A = [M for M in GL if all(q[app(M, x)] == (-q[x]) % 1 for x in V)]
mm = lambda X, Y: tuple(tuple(sum(X[i][t] * Y[t][j] for t in range(2)) % 9 for j in range(2)) for i in range(2))
I2 = ((1, 0), (0, 1))
def order(M):
    k, X = 1, M
    while X != I2: X = mm(X, M); k += 1
    return k
print("Q5 unitary symmetries: %d, element orders %s" % (len(U), dict(sorted(Counter(order(M) for M in U).items()))))
print("Q5 time-reversal symmetries: %d, element orders %s" % (len(A), dict(sorted(Counter(order(M) for M in A).items()))))
def closure(gens):
    S = {I2}; fr = [I2]
    while fr:
        nx = []
        for X in fr:
            for g in gens:
                Y = mm(X, g)
                if Y not in S: S.add(Y); nx.append(Y)
        fr = nx
    return S
inv = lambda M: next(X for X in GL if mm(M, X) == I2)
r = next(M for M in U if order(M) == 12)
dihedral = any(order(s) == 2 and mm(mm(s, r), inv(s)) == inv(r) and closure([r, s]) == set(U) for s in U)
print("Q5 the unitary group is dihedral of order 24 (a rotation of order 12 and a reflection inverting it generate it):", dihedral)
G = set(U) | set(A)
T = ((0, 1), (1, 1)); CONJ = ((1, 1), (0, 8))
print("Q5 full group order %d; generated by g = (b, a+b) and the conjugation (a, b) -> (a+b, -b): %s"
      % (len(G), len(closure([T, CONJ])) == 48 and closure([T, CONJ]) == G))
T11 = I2
for _ in range(11): T11 = mm(T11, T)
print("Q5 the conjugation c satisfies c g c^-1 = g^11 (so the full group is C24 semidirect C2 with x -> x^11):", mm(mm(CONJ, T), inv(CONJ)) == T11)
seen, orbs = set(), []
for x in V:
    if x in seen: continue
    o = {app(M, x) for M in G}; seen |= o; orbs.append(o)
for o in sorted(orbs, key=len, reverse=True):
    print("Q6 orbit of size %2d: spins %s" % (len(o), dict(sorted(Counter(str(q[x]) for x in o).items()))))
def ctype(M):
    s, out = set(), []
    for x in V:
        if x in s: continue
        c, y = 0, x
        while True:
            s.add(y); c += 1; y = app(M, y)
            if y == x: break
        out.append(c)
    return sorted(out, reverse=True)
T12 = I2
for _ in range(12): T12 = mm(T12, T)
print("Q7 g = (b, a+b): unitary %s, time-reversal %s, order %d, cycle structure %s, g^12 = %s (= -I, charge conjugation)"
      % (T in U, T in A, order(T), ctype(T), T12))
