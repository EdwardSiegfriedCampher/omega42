#!/usr/bin/env python3
"""jurisdiction.py -- Builder Rule 14 jurisdiction check (Core L-491, Part 0.0.5).

Reads records/reexamination/jurisdiction_registry.json, in which every instrument or rule adopted or changed under
L-490 to L-492 carries the answers to the five questions of Builder Rule 14, prints the table
(records/reexamination/jurisdiction_check.txt, diffed in CI) and fails when
  * any rule has Q2, Q3 or Q4 = YES, or Q5 = NO;
  * any instrument the registry names as required has no entry;
  * an instrument M3nn listed in the Core index (docs) has no entry when its number is above M309.
A new instrument therefore cannot enter the protocol without its jurisdiction stated.

Usage:
    python3 tools/jurisdiction.py                 # prints the table
    python3 tools/jurisdiction.py --check [CORE.docx]
    python3 tools/jurisdiction.py --selftest
"""
import json, os, re, sys, zipfile
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = os.path.join(ROOT, 'records', 'reexamination', 'jurisdiction_registry.json')
CORE = os.path.join(ROOT, 'docs', 'Omega42_Core_Specification_V335_Rev450_STABLE.docx')
HEAD = """BUILDER RULE 14 -- JURISDICTION CHECK (Core L-491, Part 0.0.5) | %s | %s
The five questions: Q1 what it does (INTERNAL result / PROCEDURAL integrity / INTERPRETATION / specific CORRESPONDENCE);
Q2 mandatory for every navigation although only one kind of investigation needs it?; Q3 makes an outside standard an
authority over the premise?; Q4 requires the Navigator to claim cumulative knowledge it does not possess?; Q5 does a
navigation remain complete when the optional investigation is not performed?
A rule passes when Q2, Q3 and Q4 read NO and Q5 reads YES (or N/A for a rule that is itself internal).
Generated by tools/jurisdiction.py from records/reexamination/jurisdiction_registry.json.
"""


def passes(r):
    return r['q2'] == 'NO' and r['q3'] == 'NO' and r['q4'] == 'NO' and r['q5'] in ('YES', 'N/A')


def table(reg):
    L = [HEAD % (reg['spec'], reg['date'])]
    L.append('%-48s | %-14s | Q2 | Q3 | Q4 | Q5  | RESULT' % ('INSTRUMENT / RULE', 'Q1'))
    for r in reg['rules']:
        L.append('%-48s | %-14s | %-2s | %-2s | %-2s | %-3s | %s%s' % (r['rule'][:48], r['q1'], r['q2'], r['q3'], r['q4'], r['q5'],
                 'PASS' if passes(r) else 'FAIL', ('  (%s)' % r['note']) if r.get('note') else ''))
    n = len(reg['rules']); k = sum(passes(r) for r in reg['rules'])
    L.append('')
    L.append('RESULT: %d of %d PASS.%s' % (k, n, ' No instrument makes outside validation compulsory, assigns Omega42 a global status, or treats an'
                                          '\nunperformed investigation as an internal deficiency.' if k == n else ''))
    return '\n'.join(L)


def core_instruments(path):
    if not os.path.exists(path): return []
    x = zipfile.ZipFile(path).read('word/document.xml').decode('utf-8')
    text = '\n'.join(''.join(re.findall(r'<w:t[^>]*>([^<]*)</w:t>', p)) for p in re.findall(r'<w:p[ >].*?</w:p>', x, re.S))
    return sorted({m for m in re.findall(r'^(M3\d\d|M230-[K-Z]): ', text, re.M) if m.startswith('M230-') or int(m[1:]) > 309})


def problems(reg, instruments):
    P = [r['rule'] + ': fails the check' for r in reg['rules'] if not passes(r)]
    names = ' '.join(r['rule'] for r in reg['rules'])
    for req in reg['required'] + instruments:
        if req not in names: P.append('no jurisdiction entry for %s' % req)
    return P


def selftest():
    reg = dict(spec='x', date='y', required=['M999'], rules=[dict(rule='M999 test', q1='PROCEDURAL', q2='NO', q3='NO', q4='NO', q5='YES')])
    cases = [('complete registry passes', reg, [], True),
             ('missing instrument fails', reg, ['M998'], False),
             ('outside authority fails', dict(reg, rules=[dict(reg['rules'][0], q3='YES')]), [], False),
             ('incomplete-without-investigation fails', dict(reg, rules=[dict(reg['rules'][0], q5='NO')]), [], False)]
    ok = True
    for name, r, ins, want in cases:
        got = not problems(r, ins); print('  %-40s %s' % (name, 'OK' if got == want else 'MISMATCH')); ok &= got == want
    print('JURISDICTION SELFTEST: %s' % ('PASS' if ok else 'FAIL')); return ok


if __name__ == '__main__':
    a = sys.argv[1:]
    reg = json.load(open(REG, encoding='utf-8'))
    if not a: print(table(reg)); sys.exit(0)
    if a[0] == '--selftest': sys.exit(0 if selftest() else 1)
    if a[0] == '--check':
        ins = core_instruments(a[1] if len(a) > 1 else CORE)
        P = problems(reg, ins)
        print('BUILDER RULE 14: %d rules, %d instruments above M309 in the Core index%s' % (len(reg['rules']), len(ins), ''))
        for p in P: print('  ' + p)
        print('RESULT: %s' % ('PASS' if not P else 'FAIL')); sys.exit(0 if not P else 1)
